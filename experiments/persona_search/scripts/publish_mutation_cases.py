#!/usr/bin/env python3
"""Merge genesis mutation artifacts into published case files under
results/published/mutation_cases/<bench>/case_*.json and write a MANIFEST.md.

Each case file = {bench, ctx_id, traces_source, score, parent_meta, parent_persona,
mutation_direction, hypotheses, selected_hypothesis, reasoning, child_persona,
prompt, raw} — the full proposer I/O for one mutation call.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]
SRC = _REPO / "results" / "mutation_artifacts_genesis"
DST = _REPO / "results" / "published" / "mutation_cases"

BENCHES = ("telecom", "delivery", "lic_math", "colbench")


def merge_bench(bench: str) -> list[dict]:
    bsrc = SRC / bench
    metas = {
        m["ctx_id"]: m
        for m in (json.load(open(f)) for f in sorted(bsrc.glob("ctx_*_meta.json")))
    }
    # index dumps by ctx_id extracted from the prompt's pid marker; skip
    # parse-failure dumps (parsed carries "_parse_error").
    dumps_by_ctx = {}
    for df in sorted(bsrc.glob("2026*.json")):
        dump = json.load(open(df))
        parsed = dump["parsed"]
        if "_parse_error" in parsed:
            continue
        pid = ""
        for line in dump["prompt"].splitlines():
            if "CURRENT PERSONA (" in line:
                pid = line.split("(", 1)[1].split(")", 1)[0]
                break
        ctx_id = pid.split(f"{bench}_", 1)[1] if pid.startswith(bench + "_") else pid
        # keep the first successful dump per ctx_id
        dumps_by_ctx.setdefault(ctx_id, dump)
    cases = []
    for i, ctx_id in enumerate(sorted(metas)):
        if ctx_id not in dumps_by_ctx:
            continue  # failed call, no case
        meta = metas[ctx_id]
        dump = dumps_by_ctx[ctx_id]
        parsed = dump["parsed"]
        case = {
            "bench": bench,
            "ctx_id": meta["ctx_id"],
            "traces_source": meta["traces_source"],
            "score": meta["score"],
            "n_success_traces": meta["n_success"],
            "n_failure_traces": meta["n_failure"],
            "parent_meta": meta["parent_meta"],
            "parent_persona": meta["parent_persona"],
            "mutation_direction": parsed.get("mutation_direction"),
            "hypotheses": parsed.get("hypotheses", []),
            "selected_hypothesis": parsed.get("selected_hypothesis"),
            "reasoning": parsed.get("reasoning"),
            "child_persona": parsed.get("persona_text"),
            "model": dump["model"],
            "effort": dump["effort"],
            "prompt": dump["prompt"],
            "raw": dump["raw"],
        }
        out = DST / bench / f"case_{i:02d}_{ctx_id}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(case, indent=2, ensure_ascii=False))
        cases.append(case)
    return cases


def write_manifest(all_cases: list[dict]) -> None:
    lines = [
        "# Mutation proposer case files",
        "",
        "17 mutation-proposer calls across 4 benchmarks, captured with full I/O",
        "(parent persona + mutation-context prompt + raw LLM response + parsed child).",
        "Generated by `experiments/persona_search/scripts/dump_genesis_mutations.py`",
        "using `gpt-5.2` (high) as the proposer; the proposer dump hook lives in",
        "`src/cresta/persona/mutation/proposer.py` (`MUTATION_DUMP_DIR`).",
        "",
        "## Index",
        "",
        "| bench | cases | traces source | note |",
        "|---|---:|---|---|",
    ]
    by_bench = {}
    for c in all_cases:
        by_bench.setdefault(c["bench"], []).append(c)
    notes = {
        "telecom": "real eval traces from genesis_4domain_enriched gepa_opt trajectory",
        "delivery": "real traces from run_delivery_v2 conversations, capped 6+4 (1 of 5 failed: proposer returned non-JSON)",
        "lic_math": "blind (LiC search trajectory not preserved); reasoning uses math-agent domain knowledge",
        "colbench": "blind (ColBench search trajectory not preserved); reasoning uses code-agent domain knowledge",
    }
    for b in BENCHES:
        cs = by_bench.get(b, [])
        ts = cs[0]["traces_source"] if cs else "-"
        lines.append(f"| {b} | {len(cs)} | {ts} | {notes.get(b, '')} |")
    lines += [
        "",
        "## Cases",
        "",
        "| bench | ctx_id | score | direction | n_hyp |",
        "|---|---|---|---|---:|",
    ]
    for c in all_cases:
        lines.append(
            f"| {c['bench']} | {c['ctx_id']} | {c['score']:.1%} | "
            f"{c['mutation_direction']} | {len(c['hypotheses'])} |"
        )
    lines += [
        "",
        "## Fields per case file",
        "",
        "- `parent_persona` / `parent_meta` — the persona being mutated from",
        "- `traces_source` — where the reflective conversation traces came from",
        "- `prompt` — the full mutation-context prompt sent to the proposer",
        "- `raw` — the proposer's raw LLM response (JSON text with hypotheses + reasoning + persona_text)",
        "- `hypotheses` / `selected_hypothesis` / `reasoning` — the proposer's candidate directions and choice",
        "- `child_persona` — the mutated persona text",
        "",
    ]
    (DST / "MANIFEST.md").write_text("\n".join(lines))


def main():
    all_cases = []
    for b in BENCHES:
        if (SRC / b).is_dir():
            cs = merge_bench(b)
            print(f"{b}: {len(cs)} cases")
            all_cases += cs
    write_manifest(all_cases)
    print(f"\n{len(all_cases)} cases -> {DST}")
    print(f"MANIFEST -> {DST / 'MANIFEST.md'}")


if __name__ == "__main__":
    sys.exit(main())
