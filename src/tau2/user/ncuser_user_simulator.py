"""NCUser non-collaborative user simulator, ported to τ²-bench.

Subclass of :class:`UserSimulator` that overlays NCUser's five prompt-injected
non-collaborative behaviors (emotional acts / tangential / fragment dumping /
unavailable service / cynical tone) on top of τ²-bench's native user-sim
backbone. The behavior *mechanism* (orchestration control flow + rewrite
helpers) is a faithful port of ``NCUser/tau_env/tau_bench/envs/user.py``'s
``is_pbus=False`` path; the base utterance is generated by τ²-bench's own user
sim system prompt (Option A).

Behavior switches are passed via ``llm_args["ncuser_config"]``, e.g.::

    --user ncuser --user-llm-args '{"ncuser_config":{"emotional_acts":true},
                                    "reasoning_effort":"high"}'

All five flags default to ``False`` (the ``none`` preset behaves like the
vanilla user simulator, modulo the dialogue-state bookkeeping which is inert
when no behavior is active).
"""

from __future__ import annotations

import random
from copy import deepcopy
from typing import Optional

from loguru import logger

from tau2.data_model.message import (
    AssistantMessage,
    Message,
    MultiToolMessage,
    ToolMessage,
    UserMessage,
)
from tau2.user import ncuser_behaviors as B
from tau2.user.user_simulator import UserSimulator
from tau2.utils.llm_utils import generate

STOP = "###STOP###"

_DEFAULT_CONFIG = {
    "emotional_acts": False,
    "tangential": False,
    "fragment_dumping": False,
    "unavailable_service": False,
    "is_pbus": False,
}


def _msg_to_dict(m: Message) -> dict:
    """Flatten a Message to ``{role, content}`` for dial_hist rendering."""
    content = getattr(m, "content", None)
    return {"role": getattr(m, "role", None), "content": content or ""}


class NCUserUserSimulator(UserSimulator):
    """UserSimulator + NCUser non-collaborative behavior orchestration."""

    def __init__(
        self,
        llm: str,
        instructions: Optional[str] = None,
        tools: Optional[list] = None,
        llm_args: Optional[dict] = None,
        persona_config=None,
        force_first_message_disclosure: bool = False,
    ):
        super().__init__(
            llm=llm,
            instructions=instructions,
            tools=tools,
            llm_args=llm_args,
            persona_config=persona_config,
            force_first_message_disclosure=force_first_message_disclosure,
        )

        # Pop ncuser-specific knobs out of llm_args so they aren't forwarded to
        # litellm as completion kwargs.
        cfg = dict(_DEFAULT_CONFIG)
        cfg.update(self.llm_args.pop("ncuser_config", {}) or {})
        cfg["is_pbus"] = False  # only the "ours" path is ported
        self.non_coll_config = cfg
        self.helper_model_override = self.llm_args.pop("ncuser_helper_model", None)
        # Domain selects which unavailable-service OOR generator (telecom/airline)
        # is used; defaults to telecom for backward compatibility.
        self.ncuser_domain = self.llm_args.pop("ncuser_domain", "telecom")

        # Transient behavior state (NCUser user.py:663-730)
        self.anger_triggered_last_turn = False
        self.cynical_mode = False
        self.cutoff_flag = False
        self.emotional_prob = {"delay": 0.5, "fail": 0.5}
        self.tangential_config = {
            "n_tangential": 0,
            "n_complain": 0,
            "utterance_pair": [],
        }
        self.current_tangential_utterance = None
        self.turn_idx = 0  # replaces NCUser's "Hi!" exact-string first-turn check

        # Dialogue-state decomposition (replicates NCUser's hand-authored goal_list).
        # Skipped when no behavior is active so the `none` preset is bit-for-bit
        # the vanilla user simulator (no helper LLM calls, identical cost/latency).
        self.user_goal = instructions or ""
        self.remaining_dialogue_state_list: list[str] = []
        self.used_dialogue_state_list: list[str] = []
        self.persona_paragraph = ""

        any_behavior = any(
            cfg[k]
            for k in (
                "emotional_acts",
                "tangential",
                "fragment_dumping",
                "unavailable_service",
            )
        )
        if any_behavior and self.user_goal:
            decomposed = B.decompose_instruction(
                self.user_goal, model=self._helper_model("decompose")
            )
            self.remaining_dialogue_state_list = B.build_remaining_dialogue_state(
                decomposed
            )

            # Unavailable-service OOR goals (NCUser __init__:696-714).
            if cfg["unavailable_service"]:
                try:
                    if self.ncuser_domain == "airline":
                        oor_list = B.generate_unavailable_airline_goals(
                            self.user_goal, model=self._helper_model("unavailable")
                        )
                    elif self.ncuser_domain == "retail":
                        oor_list = B.generate_unavailable_retail_goals(
                            self.user_goal, model=self._helper_model("unavailable")
                        )
                    else:
                        oor_list = B.generate_unavailable_telecom_goals(
                            self.user_goal, model=self._helper_model("unavailable")
                        )
                    if oor_list:
                        self.user_goal += (
                            f" In addition to the above conditions, if the agent is able to "
                            f"fulfill them, also include the conditions from {oor_list}.\n\n"
                        )
                        self.remaining_dialogue_state_list += deepcopy(oor_list)
                except Exception as e:  # noqa: BLE001
                    logger.warning(f"ncuser unavailable_service OOR gen failed: {e}")

            # Tangential persona paragraph (sampled once per rollout).
            if cfg["tangential"]:
                self.persona_paragraph = B.sample_persona_paragraph()

    # -- helpers ----------------------------------------------------------

    def _helper_model(self, kind: str) -> str:
        if self.helper_model_override:
            return self.helper_model_override
        # Per-helper alignment with the original NCUser model assignment.
        if kind in {"emotional", "tangential", "tangential_merge", "cynical"}:
            return "gpt-4o-mini"
        return "gpt-4.1-mini"

    def _agent_last_utterance(self, state) -> str:
        """Latest agent text utterance from state (skip tool messages)."""
        for m in reversed(state.messages):
            if isinstance(m, AssistantMessage) and not m.is_tool_call() and m.content:
                return m.content
        return ""

    # -- main override ----------------------------------------------------

    def _generate_next_message(self, message, state) -> UserMessage:
        # 1. Append incoming message to state (mirror parent user_simulator.py:261-267).
        if isinstance(message, MultiToolMessage):
            state.messages.extend(message.tool_messages)
        elif isinstance(message, ToolMessage):
            state.messages.append(message)
        elif message.has_content() or message.is_tool_call():
            state.messages.append(message)

        flipped = state.flip_roles()
        llm_messages = state.system_messages + flipped

        agent_last = self._agent_last_utterance(state)
        dial_hist = B.gpt_apply_chat_template([_msg_to_dict(m) for m in llm_messages])

        # 2. Base utterance via τ²-bench native user-sim backbone (Option A).
        assistant_message = generate(
            model=self.llm,
            messages=llm_messages,
            tools=self.tools,
            call_name="user_simulator_response",
            **self.llm_args,
        )
        content = assistant_message.content or ""
        helper_cost = 0.0

        # 3. NCUser behavior orchestration (is_pbus=False path, user.py:744-906).
        content, turn_helper_cost = self._orchestrate(
            content, dial_hist, agent_last, state
        )
        helper_cost += turn_helper_cost

        # 4. Build UserMessage (mirror parent user_simulator.py:282-302).
        user_message = UserMessage(
            role="user",
            content=content,
            cost=(assistant_message.cost or 0.0) + helper_cost,
            usage=assistant_message.usage,
            raw_data=assistant_message.raw_data,
        )
        if assistant_message.tool_calls is not None:
            user_message.tool_calls = []
            for tool_call in assistant_message.tool_calls:
                user_message.tool_calls.append(
                    type(tool_call)(
                        id=tool_call.id,
                        name=tool_call.name,
                        arguments=tool_call.arguments,
                        requestor="user",
                    )
                )
        self.turn_idx += 1
        return user_message

    # -- orchestration ----------------------------------------------------

    def _orchestrate(
        self, content: str, dial_hist: str, agent_last: str, state
    ) -> tuple[str, float]:
        cfg = self.non_coll_config
        # When no behavior is active, skip the entire overlay so the `none` preset
        # is bit-for-bit the vanilla user simulator (clean Δ baseline). The DST /
        # rest_provider / STOP bookkeeping is part of the NCUser overlay, not the
        # native backbone.
        any_behavior = any(
            cfg[k]
            for k in (
                "emotional_acts",
                "tangential",
                "fragment_dumping",
                "unavailable_service",
            )
        )
        if not any_behavior:
            return content, 0.0

        cost = 0.0
        suppress_cynical_rewrite = False
        is_no_non_coll = False

        # Cynical-mode activation: previous turn was an angry outburst and the
        # agent has now apologized (user.py:751-757).
        try:
            if self.anger_triggered_last_turn and B.is_apology(agent_last):
                self.cynical_mode = True
                self.anger_triggered_last_turn = False
        except Exception:
            pass

        # STOP + remaining dialogue state (user.py:764-781).
        if STOP in content and not cfg["is_pbus"]:
            if self.remaining_dialogue_state_list:
                content = content.replace(STOP, "")
                content = B.rest_provider(
                    dial_hist, content, self.remaining_dialogue_state_list
                )
                self.used_dialogue_state_list += deepcopy(
                    self.remaining_dialogue_state_list
                )
                self.remaining_dialogue_state_list = []
                is_no_non_coll = True
            else:
                if content.strip() != STOP:
                    if not B.is_ending(dial_hist, content.replace(STOP, "")):
                        content = content.replace(STOP, "")

        # Emotional acts (user.py:784-810).
        current_angry = False
        if (
            cfg["emotional_acts"]
            and not cfg["is_pbus"]
            and self.user_goal
            and not is_no_non_coll
        ):
            content = (
                content.replace(" please.", "")
                .replace("please ", "")
                .replace(" please", "")
            )
            if len(self.remaining_dialogue_state_list) == 0 and STOP not in content:
                if random.random() < self.emotional_prob["delay"]:
                    content = B.emotional_delay(dial_hist, self.emotional_prob["delay"])
                    current_angry = True
                    if self.emotional_prob["delay"] < 0.7:
                        self.emotional_prob["delay"] += 0.1
            else:
                result = B.system_action_classifier(
                    user_goal=self.user_goal, system_utterance=agent_last
                )
                if result:
                    if random.random() < self.emotional_prob["fail"]:
                        content = B.emotional_fail(
                            dial_hist, self.emotional_prob["fail"]
                        )
                        current_angry = True
                        if self.emotional_prob["fail"] < 0.7:
                            self.emotional_prob["fail"] += 0.1
                    self.anger_triggered_last_turn = True
                    suppress_cynical_rewrite = True

        # Tangential (user.py:812-856).
        if (
            not current_angry
            and cfg["tangential"]
            and STOP not in content
            and not cfg["is_pbus"]
            and self.user_goal
            and not is_no_non_coll
        ):
            content = self._tangential_step(content, dial_hist, agent_last)

        # Fragment dumping (user.py:859-870).
        if (
            cfg["fragment_dumping"]
            and not cfg["is_pbus"]
            and STOP not in content
            and not is_no_non_coll
        ):
            sentence_list = B.fragment_examples()
            content = B.style_transfer(content, sentence_list)
            if random.random() <= 0.5 and not self.cutoff_flag:
                cut_idx = random.sample([2, 3, 4, 5], 1)[0]
                current_cut_idx = max(int(len(content) / cut_idx), 1)
                content = content[:current_cut_idx]
                self.cutoff_flag = True
            else:
                self.cutoff_flag = False

        # Cynical rewrite (user.py:872-874).
        if self.cynical_mode and STOP not in content and not suppress_cynical_rewrite:
            content = B.rewrite_with_cynical_tone(dial_hist, content)

        # Dialogue-state tracking (user.py:877-890).
        if self.remaining_dialogue_state_list and not cfg["is_pbus"] and self.user_goal:
            used = B.dialogue_state_tracker(
                dial_hist, content, self.remaining_dialogue_state_list
            )
            if used:
                self.remaining_dialogue_state_list = [
                    s for s in self.remaining_dialogue_state_list if s not in used
                ]
                self.used_dialogue_state_list += deepcopy(used)

        # Tangential end-of-conversation verification (user.py:892-899).
        if (
            STOP in content
            and self.tangential_config["utterance_pair"]
            and self.current_tangential_utterance
        ):
            if self.tangential_config["utterance_pair"][-1].get("complain") == "<NOT>":
                verified = B.tangential_respond_verifier(
                    conversational_content=self.current_tangential_utterance,
                    system_utterance=agent_last,
                )
                self.tangential_config["utterance_pair"][-1]["complain"] = not verified

        return content, cost

    def _tangential_step(self, content: str, dial_hist: str, agent_last: str) -> str:
        """First-turn vs subsequent-turn tangential logic (user.py:812-856)."""
        # First user response -> open a tangential topic (replaces NCUser's
        # `messages[-1]['content'] == "Hi! How can I help you today?"` check).
        if self.turn_idx == 0:
            tangential_utterance = B.tangential_scenario_generator(
                self.user_goal, self.persona_paragraph
            )
            self.current_tangential_utterance = tangential_utterance
            content_list = content.split(". ")
            content_list.append(self.current_tangential_utterance)
            random.shuffle(content_list)
            content = B.tangential_merge(dial_hist, content_list)
            self.tangential_config["n_tangential"] += 1
            self.tangential_config["utterance_pair"].append(
                {"turn_idx": self.turn_idx, "utterance": content, "complain": "<NOT>"}
            )
            return content

        verified = B.tangential_respond_verifier(
            conversational_content=self.current_tangential_utterance,
            system_utterance=agent_last,
        )
        if not verified:
            if (
                self.tangential_config["utterance_pair"]
                and self.tangential_config["utterance_pair"][-1]["complain"] == "<NOT>"
            ):
                self.tangential_config["utterance_pair"][-1]["complain"] = True
            complain_utterance = B.tangential_complain_generator(
                self.current_tangential_utterance
            )
            self.tangential_config["n_complain"] += 1
            if random.random() < 0.5:
                content = complain_utterance
            else:
                content = B.tangential_merge(dial_hist, [complain_utterance, content])
        else:
            if (
                self.tangential_config["utterance_pair"]
                and self.tangential_config["utterance_pair"][-1]["complain"] == "<NOT>"
            ):
                self.tangential_config["utterance_pair"][-1]["complain"] = False
            tangential_utterance = B.tangential_scenario_generator(
                self.user_goal, self.persona_paragraph
            )
            self.current_tangential_utterance = tangential_utterance
            content_list = content.split(". ")
            content_list.append(self.current_tangential_utterance)
            random.shuffle(content_list)
            content = B.tangential_merge(dial_hist, content_list)
            self.tangential_config["n_tangential"] += 1
            self.tangential_config["utterance_pair"].append(
                {"turn_idx": self.turn_idx, "utterance": content, "complain": "<NOT>"}
            )
        return content
